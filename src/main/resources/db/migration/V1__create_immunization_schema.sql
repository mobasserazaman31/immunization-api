CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE clinics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(250) NOT NULL,
    city VARCHAR(100) NOT NULL,
    province VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE vaccination_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE slot_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id BIGINT NOT NULL REFERENCES clinics(id),
    day_of_week VARCHAR(10) NOT NULL,
    start_time VARCHAR(10) NOT NULL DEFAULT '11:00',
    end_time VARCHAR(10) NOT NULL DEFAULT '16:00',
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_till DATE NOT NULL DEFAULT DATE '9999-12-31',
    capacity INTEGER NOT NULL DEFAULT 1
        CHECK (capacity > 0),
    priority VARCHAR(20) NOT NULL DEFAULT 'DEFAULT'
        CHECK (priority IN ('DEFAULT', 'SEASONAL', 'TEMPORARY')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ex_slot_templates_same_priority_no_overlap EXCLUDE USING gist (
        clinic_id WITH =,
        day_of_week WITH =,
        priority WITH =,
        daterange(valid_from, valid_till, '[]') WITH &&
    ) WHERE (active)
);

CREATE TABLE slot_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id BIGINT NOT NULL REFERENCES clinics(id),
    override_date DATE NOT NULL,
    closed BOOLEAN NOT NULL DEFAULT TRUE,
    start_time VARCHAR(10) NOT NULL DEFAULT '11:00',
    end_time VARCHAR(10) NOT NULL DEFAULT '16:00',
    capacity INTEGER NOT NULL DEFAULT 1
        CHECK (capacity > 0),
    reason VARCHAR(250) NOT NULL DEFAULT 'Closed for the day',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_clinic_date UNIQUE (clinic_id, override_date)
);

CREATE TABLE slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id BIGINT NOT NULL REFERENCES clinics(id),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    booked_count INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN ('AVAILABLE', 'BOOKED')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_slots_clinic_start UNIQUE (clinic_id, start_time),
    CONSTRAINT ck_slots_booked_count CHECK (booked_count >= 0 AND booked_count <= capacity),
    CONSTRAINT ck_slots_status CHECK (
        (status = 'AVAILABLE' AND booked_count < capacity)
        OR (status = 'BOOKED' AND booked_count = capacity)
    )
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    slot_id BIGINT NOT NULL REFERENCES slots(id),
    service_id BIGINT NOT NULL REFERENCES vaccination_services(id),

    patient_first_name VARCHAR(100) NOT NULL,
    patient_last_name VARCHAR(100) NOT NULL,
    patient_date_of_birth DATE NOT NULL,
    patient_ohip_number VARCHAR(12) NOT NULL,

    guardian_name VARCHAR(200) NOT NULL,
    guardian_email VARCHAR(254) NOT NULL,
    guardian_phone VARCHAR(30),

    status VARCHAR(20) NOT NULL DEFAULT 'BOOKED'
        CHECK (status IN ('BOOKED', 'CANCELLED')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE task_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_name VARCHAR(150) NOT NULL UNIQUE,
    completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_slot_templates_clinic_day_validity
    ON slot_templates(clinic_id, day_of_week, valid_from, valid_till);

CREATE INDEX idx_slot_overrides_clinic_date
    ON slot_overrides(clinic_id, override_date);

CREATE INDEX idx_slots_clinic_start_status
    ON slots(clinic_id, start_time, status)
    WHERE active = TRUE;

CREATE INDEX idx_appointments_slot
    ON appointments(slot_id);

CREATE INDEX idx_appointments_guardian_email
    ON appointments(guardian_email);

CREATE UNIQUE INDEX uq_appointments_patient_service_booked
    ON appointments(patient_ohip_number, service_id)
    WHERE status = 'BOOKED';

