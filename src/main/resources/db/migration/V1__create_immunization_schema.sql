
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE clinics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(250) NOT NULL,
    city VARCHAR(100) NOT NULL,
    province VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE vaccination_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    duration_minutes INTEGER NOT NULL
        CHECK (duration_minutes > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE appointment_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id BIGINT NOT NULL REFERENCES clinics(id),
    start_time TIMESTAMPTZ NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_clinic_slot_start UNIQUE (clinic_id, start_time)
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    slot_id BIGINT NOT NULL REFERENCES appointment_slots(id),
    service_id BIGINT NOT NULL REFERENCES vaccination_services(id),

    patient_first_name VARCHAR(100) NOT NULL,
    patient_last_name VARCHAR(100) NOT NULL,
    patient_date_of_birth DATE NOT NULL,

    guardian_name VARCHAR(200) NOT NULL,
    guardian_email VARCHAR(254) NOT NULL,
    guardian_phone VARCHAR(30),

    status VARCHAR(20) NOT NULL DEFAULT 'BOOKED'
        CHECK (status IN ('BOOKED', 'CANCELLED')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- One slot cannot have two non-cancelled bookings.
CREATE UNIQUE INDEX uq_active_booking_slot
    ON appointments(slot_id)
    WHERE status = 'BOOKED';

CREATE INDEX idx_slots_clinic_start
    ON appointment_slots(clinic_id, start_time);

CREATE INDEX idx_appointments_guardian_email
    ON appointments(guardian_email);
